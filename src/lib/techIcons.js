const normalize = (name) =>
  String(name || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[\s_\-()]/g, "");

const INDEX = new Map();
ALIASES.forEach(([icon, names]) => {
  names.forEach((n) => INDEX.set(normalize(n), icon));
});

const cache = new Map();

/**
 * Busca el logo de una tecnología por su nombre ("Next.js 15", "PostgreSQL (Neon)").
 * @returns {{ title: string, hex: string, path: string } | null}
 */
export function getTechIcon(name) {
  if (cache.has(name)) return cache.get(name);

  const full = normalize(name);
  let icon = INDEX.get(full) || null;

  if (!icon) {
    // Prueba palabra por palabra y sin versión: "Prisma ORM", "React 19", "Laravel (PHP)"
    const words = String(name || "")
      .split(/[\s/+,()]+/)
      .map((w) => normalize(w.replace(/\d+(\.\d+)*$/, "")))
      .filter(Boolean);
    for (const word of words) {
      icon = INDEX.get(word);
      if (icon) break;
    }
    // Pares de palabras: "Spring Boot", "GitHub Actions", "Cloud Run"
    if (!icon) {
      for (let i = 0; i < words.length - 1 && !icon; i++) {
        icon = INDEX.get(words[i] + words[i + 1]) || null;
      }
    }
  }

  const result = icon
    ? { title: icon.title, hex: icon.hex, path: icon.path }
    : null;
  cache.set(name, result);
  return result;
}
